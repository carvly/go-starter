// Package meta 从 api/admin.yaml 生成 web/admin/src/api/meta.gen.ts：每个 schema 的字段文案和
// 枚举文案、请求体的表单校验（zod）、列表接口 URL 查询参数的校验。前端的文案和校验因此只在 spec
// 里写一次。只支持 spec 实际用到的写法，遇到不支持的直接报错，不静默生成错误的代码。
package meta

import (
	"cmp"
	"errors"
	"fmt"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v4"
)

const header = `// Code generated by tools/gen from api/admin.yaml. DO NOT EDIT.
// 改了 api/admin.yaml 之后跑 make generate；约定见 docs/agents/admin.md 的"字段文案与校验（meta.gen.ts）"。

`

const (
	schemaRef = "#/components/schemas/"
	paramRef  = "#/components/parameters/"
)

// 前端模块，按输出顺序：第三方在前，项目内的在后，中间空一行。
var modules = []string{"zod", "@/lib/field-schemas", "@/lib/search"}

type gen struct {
	schemas map[string]*schema
	params  map[string]*parameter
	errs    []string
	uses    map[string]map[string]bool
}

type field struct {
	name     string
	s        *schema
	required bool
}

type listOp struct {
	loc, id string
	params  []*parameter
}

// Generate 返回 meta.gen.ts 的内容。spec 有问题时一次报出全部错误，每条写明位置和改法。
func Generate(spec []byte) ([]byte, error) {
	var doc document
	if err := yaml.Unmarshal(spec, &doc); err != nil {
		return nil, fmt.Errorf("解析 spec：%w", err)
	}
	g := &gen{schemas: map[string]*schema{}, params: doc.Components.Parameters, uses: map[string]map[string]bool{}}
	for _, e := range doc.Components.Schemas {
		g.schemas[e.key] = e.val
	}
	ops, bodies := g.operations(doc)

	var body strings.Builder
	for _, e := range doc.Components.Schemas {
		g.check("components.schemas."+e.key, e.val)
	}
	// 枚举先输出：对象的字段引用它们的文案。
	for _, e := range doc.Components.Schemas {
		if len(e.val.Enum) > 0 {
			g.writeEnum(&body, e.key, e.val)
		}
	}
	for _, e := range doc.Components.Schemas {
		if len(e.val.Enum) == 0 {
			g.writeObject(&body, e.key, e.val, bodies[e.key])
		}
	}
	for _, op := range ops {
		g.writeSearch(&body, op)
	}
	if len(g.errs) > 0 {
		return nil, errors.New(strings.Join(g.errs, "\n"))
	}

	var out strings.Builder
	out.WriteString(header)
	g.writeImports(&out)
	out.WriteString(body.String())
	return []byte(out.String()), nil
}

func (g *gen) fail(loc, problem, fix string) {
	g.errs = append(g.errs, fmt.Sprintf("api/admin.yaml %s：%s。改法：%s", loc, problem, fix))
}

func (g *gen) use(module, name string) {
	if g.uses[module] == nil {
		g.uses[module] = map[string]bool{}
	}
	g.uses[module][name] = true
}

// operations 找出作为请求体的 schema，以及带查询参数的 GET 操作。
func (g *gen) operations(doc document) ([]listOp, map[string]bool) {
	var ops []listOp
	bodies := map[string]bool{}
	for _, p := range doc.Paths {
		for _, m := range p.val {
			switch m.key {
			case "get", "post", "put", "patch", "delete":
			default:
				continue
			}
			loc := fmt.Sprintf("paths.%s.%s", p.key, m.key)
			var op operation
			if err := m.val.Decode(&op); err != nil {
				g.fail(loc, err.Error(), "按 OpenAPI 的写法修正")
				continue
			}
			if op.RequestBody != nil {
				for _, c := range op.RequestBody.Content {
					name, ok := strings.CutPrefix(c.Schema.Ref, schemaRef)
					if !ok {
						g.fail(loc+".requestBody", "请求体没有引用 components.schemas", "把请求体的 schema 定义在 components.schemas 里，这里写 $ref")
						continue
					}
					bodies[name] = true
				}
			}
			if m.key == "get" {
				var params []*parameter
				for _, prm := range op.Parameters {
					if r := g.param(loc, prm); r != nil && r.In == "query" {
						params = append(params, r)
					}
				}
				if len(params) > 0 {
					ops = append(ops, listOp{loc: loc, id: op.OperationID, params: params})
				}
			}
		}
	}
	return ops, bodies
}

func (g *gen) param(loc string, p *parameter) *parameter {
	if p.Ref == "" {
		return p
	}
	name, _ := strings.CutPrefix(p.Ref, paramRef)
	if r, ok := g.params[name]; ok {
		return r
	}
	g.fail(loc, "找不到参数 "+p.Ref, "在 components.parameters 里定义它")
	return nil
}

// deref 返回 $ref 指向的 schema；不是引用时原样返回。
func (g *gen) deref(loc string, s *schema) *schema {
	if s == nil || s.Ref == "" {
		return s
	}
	if t, ok := g.schemas[refName(s.Ref)]; ok {
		return t
	}
	g.fail(loc, "找不到 "+s.Ref, "在 components.schemas 里定义它")
	return &schema{}
}

func refName(ref string) string {
	name, _ := strings.CutPrefix(ref, schemaRef)
	return name
}

// check 检查前端依赖的约定：每个属性有 title，枚举的每个取值有文案，x-field 用法正确。
func (g *gen) check(loc string, s *schema) {
	if s == nil {
		return
	}
	if len(s.Enum) > 0 {
		g.checkLabels(loc, s)
	}
	switch s.Field {
	case "":
	case "text":
		if s.Type != "string" {
			g.fail(loc, "x-field: text 只能用于 type: string", "去掉 x-field，或者把类型改成 string")
		}
	case "money":
		if s.Type != "integer" {
			g.fail(loc, "x-field: money 只能用于 type: integer（单位：分）", "把类型改成 integer、format: int64")
		}
	default:
		g.fail(loc, fmt.Sprintf("x-field 不支持 %q", s.Field), "只能写 text（长文本，用多行输入框）或 money（金额，单位：分）")
	}
	for _, p := range s.Properties {
		ploc := loc + ".properties." + p.key
		if p.val.Title == "" {
			g.fail(ploc, "缺少 title", "加上 title: <中文名>，它是前端表单的标签、列表的表头和详情页的字段名")
		}
		if strings.HasSuffix(p.key, "_cents") != (p.val.Field == "money") {
			g.fail(ploc, "金额字段要同时满足两条：名字以 _cents 结尾、写 x-field: money", "是金额就把两条都补上；不是金额就去掉名字里的 _cents 和 x-field: money")
		}
		g.check(ploc, p.val)
	}
	for i, part := range s.AllOf {
		g.check(fmt.Sprintf("%s.allOf[%d]", loc, i), part)
	}
	g.check(loc+".items", s.Items)
}

func (g *gen) checkLabels(loc string, s *schema) {
	if len(s.EnumLabels) == 0 {
		g.fail(loc, "枚举缺少 x-enum-labels", "加上 x-enum-labels，为每个取值写中文文案（如 active: 正常），它是下拉框、筛选和徽标上显示的文字")
		return
	}
	for _, l := range s.EnumLabels {
		if !slices.Contains(s.Enum, l.key) {
			g.fail(loc, fmt.Sprintf("x-enum-labels 里的 %s 不是枚举取值", l.key), "删掉这一行，或者把它加进 enum")
		}
	}
	for _, v := range s.Enum {
		if g.label(s, v) == "" {
			g.fail(loc, fmt.Sprintf("枚举取值 %s 在 x-enum-labels 里没有文案", v), fmt.Sprintf("在 x-enum-labels 下加一行 %s: <中文>", v))
		}
	}
}

func (g *gen) label(s *schema, v string) string {
	for _, l := range s.EnumLabels {
		if l.key == v {
			return l.val
		}
	}
	return ""
}

func (g *gen) writeEnum(b *strings.Builder, name string, s *schema) {
	values := make([]string, len(s.Enum))
	for i, v := range s.Enum {
		values[i] = quote(v)
	}
	fmt.Fprintf(b, "\nexport const %sMeta = {\n", camel(name))
	fmt.Fprintf(b, "  values: [%s],\n", strings.Join(values, ", "))
	fmt.Fprintf(b, "  labels: %s,\n", g.labels(s))
	b.WriteString("} as const;\n")
}

func (g *gen) labels(s *schema) string {
	kv := make([]string, len(s.Enum))
	for i, v := range s.Enum {
		kv[i] = key(v) + ": " + quote(g.label(s, v))
	}
	return "{ " + strings.Join(kv, ", ") + " }"
}

// flatten 展开 allOf，按书写顺序返回全部字段。
func (g *gen) flatten(loc string, s *schema) []field {
	var fs []field
	for i, part := range s.AllOf {
		fs = append(fs, g.flatten(fmt.Sprintf("%s.allOf[%d]", loc, i), g.deref(loc, part))...)
	}
	for _, p := range s.Properties {
		fs = append(fs, field{name: p.key, s: p.val, required: slices.Contains(s.Required, p.key)})
	}
	return fs
}

func (g *gen) writeObject(b *strings.Builder, name string, s *schema, isBody bool) {
	loc := "components.schemas." + name
	fields := g.flatten(loc, s)
	if len(fields) == 0 {
		return
	}
	fmt.Fprintf(b, "\nexport const %sMeta = {\n  fields: {\n", camel(name))
	for _, f := range fields {
		entry := "title: " + quote(f.s.Title)
		t := g.deref(loc, f.s)
		// min / max：字符串是字符数，整数是数值，金额的单位是分；页面的说明文字用它们，不再抄一遍数字。
		for _, c := range []struct {
			k string
			v *int64
		}{{"min", cmp.Or(t.MinLength, t.Minimum)}, {"max", cmp.Or(t.MaxLength, t.Maximum)}} {
			if c.v != nil {
				entry += fmt.Sprintf(", %s: %d", c.k, *c.v)
			}
		}
		if len(t.Enum) > 0 {
			if f.s.Ref != "" {
				entry += fmt.Sprintf(", labels: %sMeta.labels", camel(refName(f.s.Ref)))
			} else {
				entry += ", labels: " + g.labels(t)
			}
		}
		fmt.Fprintf(b, "    %s: { %s },\n", key(f.name), entry)
	}
	b.WriteString("  },\n")
	if isBody {
		g.use("zod", "z")
		b.WriteString("  form: z.object({\n")
		for _, f := range fields {
			fmt.Fprintf(b, "    %s: %s,\n", key(f.name), g.formField(loc+".properties."+f.name, f))
		}
		b.WriteString("  }),\n")
	}
	b.WriteString("} as const;\n")
}

// formField 是表单字段的 zod 规则，和 src/components/form 的字段组件对应：输入框里的值是字符串，
// 规则负责校验并转换成请求体要的类型，所以 parse 的结果就是请求体。
func (g *gen) formField(loc string, f field) string {
	s := g.deref(loc, f.s)
	title := quote(f.s.Title)
	switch {
	case len(s.Enum) > 0:
		g.use("@/lib/field-schemas", "enumInput")
		return "enumInput(" + g.enumValues(f.s, s) + ", " + object("title", title, "required", boolOpt(f.required)) + ")"
	case s.Type == "string" && s.Format == "date":
		g.use("@/lib/field-schemas", "dateInput")
		return "dateInput(" + object("title", title, "required", boolOpt(f.required)) + ")"
	case s.Type == "string" && s.Format == "date-time":
		g.use("@/lib/field-schemas", "dateTimeInput")
		return "dateTimeInput(" + object("title", title, "required", boolOpt(f.required)) + ")"
	case s.Type == "string" && (s.Format == "" || s.Format == "password"):
		g.use("@/lib/field-schemas", "textInput")
		opts := []string{"title", title, "required", boolOpt(f.required), "min", intOpt(s.MinLength), "max", intOpt(s.MaxLength)}
		if s.Format == "password" {
			opts = append(opts, "trim", "false")
		}
		return "textInput(" + object(opts...) + ")"
	case s.Type == "integer" && s.Field == "money":
		g.use("@/lib/field-schemas", "moneyInput")
		return "moneyInput(" + object("title", title, "required", boolOpt(f.required), "min", intOpt(s.Minimum), "max", intOpt(s.Maximum)) + ")"
	case s.Type == "integer" && f.name == "version":
		// 乐观锁的版本号不是用户输入，打开表单时读到什么就原样提交。
		return "z.number().int()"
	case s.Type == "integer":
		g.use("@/lib/field-schemas", "intInput")
		return "intInput(" + object("title", title, "required", boolOpt(f.required), "min", intOpt(s.Minimum), "max", intOpt(s.Maximum)) + ")"
	case s.Type == "boolean":
		return "z.boolean()"
	case s.Type == "array" && s.Items != nil:
		items := g.deref(loc, s.Items)
		switch {
		case len(items.Enum) > 0:
			return "z.array(z.enum(" + g.enumValues(s.Items, items) + "))"
		case items.Type == "string":
			return "z.array(z.string())"
		}
	}
	g.fail(loc, fmt.Sprintf("表单校验不支持 type: %s、format: %s", s.Type, s.Format), "在 tools/gen/meta 里给这种写法补上对应的表单规则和测试，或者不把它放进请求体")
	return "z.never()"
}

// enumValues 引用枚举 schema 的取值，内联的枚举直接写出取值。
func (g *gen) enumValues(ref, s *schema) string {
	if ref.Ref != "" {
		return camel(refName(ref.Ref)) + "Meta.values"
	}
	values := make([]string, len(s.Enum))
	for i, v := range s.Enum {
		values[i] = quote(v)
	}
	return "[" + strings.Join(values, ", ") + "]"
}

// writeSearch 生成列表页 URL 查询参数的校验（validateSearch 直接使用）。每页条数和 cursor 不进
// URL；时间范围在 URL 里是日期（yyyy-mm-dd），页面用 dayRange 换算成带时区的时间再请求。
func (g *gen) writeSearch(b *strings.Builder, op listOp) {
	var size int
	for _, p := range op.params {
		if p.Name == "size" && p.Schema != nil {
			size, _ = p.Schema.Default.(int)
		}
	}
	var entries []string
	pageSize := 0
	for _, p := range op.params {
		loc := op.loc + ".parameters." + p.Name
		s := g.deref(loc, p.Schema)
		if s == nil {
			g.fail(loc, "参数缺少 schema", "补上 schema")
			continue
		}
		var expr string
		switch {
		case p.Name == "size" || p.Name == "limit" || p.Name == "cursor":
			continue
		case p.Name == "page":
			if size <= 0 {
				g.fail(loc, "有 page 参数但没有带默认值的 size 参数", "加上 $ref: \"#/components/parameters/Size\"")
				continue
			}
			pageSize = size
			g.use("@/lib/search", "pageSearch")
			expr = fmt.Sprintf("pageSearch(%d)", size)
		case s.Type == "string" && (s.Format == "date-time" || s.Format == "date"):
			g.use("@/lib/search", "daySearch")
			expr = "daySearch"
		case s.Type == "string" && len(s.Enum) > 0:
			g.use("@/lib/search", "enumSearch")
			expr = "enumSearch(" + g.enumValues(p.Schema, s) + ")"
		case s.Type == "boolean":
			g.use("@/lib/search", "boolSearch")
			expr = "boolSearch"
		case s.Type == "string" && s.Format == "uuid":
			g.use("@/lib/search", "uuidSearch")
			expr = "uuidSearch"
		case s.Type == "string" && s.Format == "" && len(s.Enum) == 0:
			g.use("@/lib/search", "textSearch")
			expr = "textSearch"
		case s.Type == "array" && s.Items != nil && len(g.deref(loc, s.Items).Enum) > 0:
			g.use("@/lib/search", "enumListSearch")
			expr = "enumListSearch(" + g.enumValues(s.Items, g.deref(loc, s.Items)) + ")"
		default:
			g.fail(loc, fmt.Sprintf("列表的查询参数不支持 type: %s、format: %s", s.Type, s.Format), "在 tools/gen/meta 里给这种写法补上对应的规则和测试，以及 src/lib/search.ts 里的校验")
			continue
		}
		entries = append(entries, fmt.Sprintf("    %s: %s,\n", key(p.Name), expr))
	}
	if len(entries) == 0 {
		return
	}
	if op.id == "" {
		g.fail(op.loc, "缺少 operationId", "加上 operationId")
		return
	}
	g.use("zod", "z")
	fmt.Fprintf(b, "\nexport const %sMeta = {\n  search: z.object({\n%s  }),\n", op.id, strings.Join(entries, ""))
	if pageSize > 0 {
		fmt.Fprintf(b, "  pageSize: %d,\n", pageSize)
	}
	b.WriteString("} as const;\n")
}

func (g *gen) writeImports(b *strings.Builder) {
	external := true
	for _, m := range modules {
		names := g.uses[m]
		if len(names) == 0 {
			continue
		}
		if external && strings.HasPrefix(m, "@/") {
			b.WriteString("\n")
			external = false
		}
		sorted := make([]string, 0, len(names))
		for n := range names {
			sorted = append(sorted, n)
		}
		slices.Sort(sorted)
		fmt.Fprintf(b, "import { %s } from %s;\n", strings.Join(sorted, ", "), quote(m))
	}
}

func camel(name string) string {
	return strings.ToLower(name[:1]) + name[1:]
}

var ident = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func key(s string) string {
	if ident.MatchString(s) {
		return s
	}
	return quote(s)
}

func quote(s string) string {
	return strconv.Quote(s)
}

func boolOpt(v bool) string {
	if v {
		return "true"
	}
	return ""
}

func intOpt(v *int64) string {
	if v == nil {
		return ""
	}
	return strconv.FormatInt(*v, 10)
}

// object 把成对的键和值写成对象字面量，值为空的键省略。
func object(kv ...string) string {
	var parts []string
	for i := 0; i+1 < len(kv); i += 2 {
		if kv[i+1] != "" {
			parts = append(parts, kv[i]+": "+kv[i+1])
		}
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}
